"""Pydantic mirrors of the backend's zod LLM-output schemas (llm/schemas/*.ts).

These are the canonical shapes every LLM-proposed output is forced into via LangChain's
with_structured_output(), regardless of which provider in LLM_MODELS answers — kept
field-for-field identical to strategy-params.schema.ts / live-decision.schema.ts so a
strategy generated by the worker is indistinguishable from one generated by the backend.
"""
from __future__ import annotations

from typing import Literal, Optional

from pydantic import BaseModel, Field


class IndicatorConfig(BaseModel):
    emaFastPeriod: int = Field(..., ge=2, le=100, description="Fast EMA period in candles")
    emaSlowPeriod: int = Field(..., ge=5, le=300, description="Slow EMA period in candles")
    rsiPeriod: Optional[int] = Field(
        None, ge=2, le=50, description="RSI lookback period, if the strategy uses RSI"
    )
    rsiBuyThreshold: Optional[float] = Field(None, ge=0, le=100)
    rsiSellThreshold: Optional[float] = Field(None, ge=0, le=100)
    stopLossPct: float = Field(..., ge=0.1, le=20, description="Stop-loss as a percent, e.g. 1.5 for 1.5%")
    takeProfitPct: float = Field(..., ge=0.1, le=50, description="Take-profit as a percent, e.g. 3.5 for 3.5%")


class StrategyParams(BaseModel):
    """Canonical shape every LLM-proposed strategy must be forced into (mirrors
    StrategyParamsSchema)."""

    strategyName: str = Field(..., description="Short human-readable name for this strategy variant")
    indicatorConfig: IndicatorConfig
    reasoning: str = Field(..., description="Brief rationale for these parameter choices")


class LiveDecision(BaseModel):
    """Mode B live-decision output (mirrors LiveDecisionSchema)."""

    action: Literal["BUY", "SELL", "HOLD"] = Field(..., description="The trading action to take right now")
    reasoning: str = Field(..., description="Brief rationale for this decision")
